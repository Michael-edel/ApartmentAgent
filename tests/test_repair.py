def test_complex_section_ends_at_explicit_apartment_heading():
    description = "Описание ЖК\nХороший ремонт в холле.\nОписание квартиры\nКвартира без ремонта."
    assert parse_repair_description(description) == ("без ремонта", "Квартира без ремонта.")


def test_evidence_is_bounded_without_inventing_or_rewriting_a_quote():
    description = "Квартира " + "просторная " * 80 + "с хорошим ремонтом."
    result = parse_repair_description(description)
    assert result and result[0] == "хороший ремонт"
    assert len(result[1]) <= 500 and result[1] in description
