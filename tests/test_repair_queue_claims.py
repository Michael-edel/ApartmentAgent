import pytest

from app.repair import parse_repair_description


@pytest.mark.parametrize("description,condition,evidence", [
    (
        "Этажность – 2 (5), состояние – удовлетворительное",
        "удовлетворительное состояние",
        "2 (5), состояние – удовлетворительное",
    ),
    ("Состояние квартиры: удовлетворительное", "удовлетворительное состояние", "Состояние квартиры: удовлетворительное"),
    ("Состояние — удовлетворительное.", "удовлетворительное состояние", "Состояние — удовлетворительное."),
    ("✔ Квартира с ремонтом", "с ремонтом", "✔ Квартира с ремонтом"),
    ("Продаю квартиру с ремонтом.", "с ремонтом", "Продаю квартиру с ремонтом."),
    ("продам квартиру в хорошем состояни.", "хорошее состояние", "продам квартиру в хорошем состояни."),
])
def test_explicit_claims_from_normalized_queue_descriptions(description, condition, evidence):
    assert parse_repair_description(description) == (condition, evidence)
    assert evidence in description


