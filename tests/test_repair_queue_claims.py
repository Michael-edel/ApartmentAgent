@pytest.mark.parametrize("description,condition", [
    ("Квартира с ремонтом.\nКвартира с хорошим ремонтом.", "хороший ремонт"),
    ("Квартира с ремонтом.\nСостояние квартиры: удовлетворительное.", "удовлетворительное состояние"),
    ("Квартира с ремонтом.\nКвартира в хорошем состоянии.", "хорошее состояние"),
    ("Описание ЖК\nМебель в хорошем состоянии.\nОписание квартиры\n✔ Квартира с ремонтом", "с ремонтом"),
])
def test_generic_renovation_does_not_invent_quality_or_override_specific_condition(description, condition):
    result = parse_repair_description(description)
    assert result is not None and result[0] == condition
    assert result[1] in description and len(result[1]) <= 500


